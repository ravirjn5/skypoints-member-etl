CALL RAW.SP_LOAD_RAW_MEMBER($LID);    -- expect INS 11
CALL STG.SP_LOAD_MEMBER($LID);        -- expect INS 11
CALL MAIN.SP_VALIDATE_MEMBER($LID);   -- no error; 2 WARN rows in the error log
CALL MAIN.SP_PUBLISH_MEMBER($LID);    -- expect INS 3 (Aiko, Lucas, Ravi into USA), UPD 1 (Elena), DEL 1 (Ravi out of India)
UPDATE CTRL.LOAD_CONTROL SET LOAD_STATUS = 'C', LOAD_ET = CURRENT_TIMESTAMP() WHERE LOAD_ID = $LID;

SELECT * FROM V_COUNTRY_TABLES ORDER BY TBL, MEMBER_ID;
-- expect: Ravi in TABLE_USA only (not INDIA), Elena PLT, Nora still LOAD_ID 1 (not rewritten),
--         Aiko in PHILIPPINES, Lucas in USA. Liam, Omar, Priya, Zara nowhere.

SELECT * FROM MAIN.MEMBER_COUNTRY_MOVE;                          -- expect Ravi IND -> USA
SELECT * FROM DQ.MEMBER_QUARANTINE WHERE LOAD_ID = $LID;          -- expect Priya, Omar, Zara, Liam x2
SELECT * FROM CTRL.PROCESS_ERROR_LOG WHERE LOAD_ID = $LID;        -- expect 2 WARN (reject rate, duplicates)

