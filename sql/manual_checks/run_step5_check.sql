/* run_step5_check.sql
   Manual run of validate + publish, before the master proc exists.
   Run the parts one at a time and compare with the expected results. */

USE DATABASE SKYPOINTS_DB;

-- a quick way to see all five country tables together
CREATE OR REPLACE TEMPORARY VIEW V_COUNTRY_TABLES AS
          SELECT 'TABLE_USA'         AS TBL, MEMBER_ID, MEMBER_NAME, TIER_CODE, COUNTRY_CODE, STALE_MEMBER, LOAD_ID, INSERT_DATE, LAST_UPDATE_DATE FROM MAIN.TABLE_USA
UNION ALL SELECT 'TABLE_INDIA',       MEMBER_ID, MEMBER_NAME, TIER_CODE, COUNTRY_CODE, STALE_MEMBER, LOAD_ID, INSERT_DATE, LAST_UPDATE_DATE FROM MAIN.TABLE_INDIA
UNION ALL SELECT 'TABLE_PHILIPPINES', MEMBER_ID, MEMBER_NAME, TIER_CODE, COUNTRY_CODE, STALE_MEMBER, LOAD_ID, INSERT_DATE, LAST_UPDATE_DATE FROM MAIN.TABLE_PHILIPPINES
UNION ALL SELECT 'TABLE_CANADA',      MEMBER_ID, MEMBER_NAME, TIER_CODE, COUNTRY_CODE, STALE_MEMBER, LOAD_ID, INSERT_DATE, LAST_UPDATE_DATE FROM MAIN.TABLE_CANADA
UNION ALL SELECT 'TABLE_AUSTRALIA',   MEMBER_ID, MEMBER_NAME, TIER_CODE, COUNTRY_CODE, STALE_MEMBER, LOAD_ID, INSERT_DATE, LAST_UPDATE_DATE FROM MAIN.TABLE_AUSTRALIA;

/* ===== PART A: finish day 1 (the load from step 4, still in staging) ===== */
SET LID = (SELECT MAX(LOAD_ID) FROM CTRL.LOAD_CONTROL);
CALL MAIN.SP_VALIDATE_MEMBER($LID);   -- expect 0,0,0 and no error
CALL MAIN.SP_PUBLISH_MEMBER($LID);    -- expect INS 5, UPD 0, DEL 0
UPDATE CTRL.LOAD_CONTROL SET LOAD_STATUS = 'C', LOAD_ET = CURRENT_TIMESTAMP() WHERE LOAD_ID = $LID;

SELECT * FROM V_COUNTRY_TABLES ORDER BY TBL, MEMBER_ID;
-- expect: USA Elena, INDIA Ravi, PHILIPPINES Mateo, CANADA Nora, AUSTRALIA Jacob

/* ===== PART B: day 2 =====
   Upload data/test_scenarios/members_20240116_010000.txt to path: members */
